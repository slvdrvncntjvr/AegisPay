// Records the actual anonymous public site. Never loads environment files or signs.
import {createRequire} from 'node:module';
import {mkdir, copyFile, writeFile, readFile} from 'node:fs/promises';
import {resolve} from 'node:path';
const require = createRequire(resolve('../../../node_modules/@playwright/test/package.json'));
const {chromium} = require('@playwright/test');
const origin = 'https://aegispay-live.vercel.app';
await mkdir('public', {recursive:true});
await mkdir('captures', {recursive:true});
const browser = await chromium.launch({executablePath:process.env.DECK_BROWSER_EXECUTABLE || 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
const context = await browser.newContext({viewport:{width:1440,height:810},recordVideo:{dir:'captures',size:{width:1440,height:810}}});
const page = await context.newPage();
const errors=[]; page.on('pageerror', e=>errors.push(e.message));
const response=await page.goto(origin,{waitUntil:'networkidle'});
if(response.status()!==200) throw Error(`Public site returned ${response.status()}`);
await page.waitForTimeout(2500);
await page.getByRole('tab',{name:'Policy',exact:true}).click();
await page.waitForTimeout(4500);
await page.screenshot({path:'public/policy.png'});
await page.getByRole('tab',{name:'Run',exact:true}).click();
await page.waitForTimeout(4500);
await page.screenshot({path:'public/run.png'});
await page.getByRole('tab',{name:'Audit',exact:true}).click();
await page.waitForTimeout(4500);
await page.screenshot({path:'public/audit.png'});
const links=await page.locator('a').evaluateAll(as=>as.map(a=>({text:a.textContent,href:a.href})));
const health=await (await context.request.get(`${origin}/api/health`)).json();
if(health.status!=='ok'||health.network!=='testnet') throw Error('Unexpected health');
const desktopOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
await context.close();
await copyFile(await page.video().path(),'public/website.webm');
const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:1});
const mp=await mobile.newPage();await mp.goto(origin,{waitUntil:'networkidle'});
await mp.screenshot({path:'public/mobile.png',fullPage:true});
const mobileOverflow=await mp.evaluate(()=>document.documentElement.scrollWidth>390);
await mobile.close();
// Render the exact redacted saved artifact, explicitly as a replay, for readable filming.
const evidence=JSON.parse(await readFile('../../evidence/testnet/spike-c080d947-714b-43cf-92d0-ad9ed7c01439-1794064999769.json','utf8'));
await writeFile('public/saved-evidence.json',JSON.stringify(evidence,null,2));
await writeFile('captures/site-check.json',JSON.stringify({observedAt:new Date().toISOString(),origin,health,desktopOverflow,mobileOverflow,errors,links},null,2));
await browser.close();
if(errors.length||desktopOverflow||mobileOverflow) throw Error('Site checks need review');
console.log('PASS: actual public Policy/Run/Audit capture, mobile layout, health and links');
